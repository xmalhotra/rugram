import assert from 'node:assert/strict';
import {mockPhoneUser} from '../src/lib/store';
import {adminCatalogSnapshot,submitItem,reviewItem,updateCuratedEvent,mobileBootstrap} from '../src/lib/mobile-store';
import {changeRegistration,registrationView,manageHostedEvent,eventInviteInbox} from '../src/lib/event-registration-store';
import {hostedDemoEvent} from '../shared/hosted-demo-event';
import {creatorEventSchema,eventLinkSchema} from '../src/lib/event-validation';
process.env.RUGRAM_DEMO_MODE='true';
async function main(){
  const admin=await mockPhoneUser('+12025550103');const creator=await mockPhoneUser('+12025550102');
  const input={...hostedDemoEvent(),title:'DEMO · Isolated 100-place test',editorialPriority:{score:3,reason:'Isolated hosted-event integration test, not a real listing.'}};
  const {editorialPriority,...proposal}=eventLinkSchema.parse(inputFor(input));void editorialPriority;
  creatorEventSchema.parse(proposal);
  await submitItem(creator,{...proposal,id:'',createdBy:'',status:'pending',capacity:0,price:0,simulation:true},'hosted-capacity-integration');
  const event=(await adminCatalogSnapshot(admin)).find(item=>item.title===input.title&&item.createdBy===creator.id)!;
  const users=await Promise.all(Array.from({length:102},(_,index)=>mockPhoneUser('+1202555'+String(300+index).padStart(4,'0'))));
  await assert.rejects(()=>changeRegistration(users[0],event.id,'request'),/not available/);
  await assert.rejects(()=>reviewItem(creator,event.id,'published'),/Admin access/);
  await assert.rejects(()=>reviewItem(admin,event.id,'published'),/verify sources/);
  await updateCuratedEvent(admin,event.id,inputFor(input));await reviewItem(admin,event.id,'published');
  assert.equal((await registrationView(creator,event.id)).canManage,true);
  await Promise.all(users.slice(0,101).map(user=>changeRegistration(user,event.id,'request')));
  await changeRegistration(users[0],event.id,'request');
  assert.equal((await registrationView(admin,event.id)).pendingCount,101);
  assert.equal((await eventInviteInbox(creator)).requests.length,100);
  assert.equal((await eventInviteInbox(creator)).total,101);
  assert.ok((await eventInviteInbox(admin)).requests.some(item=>item.eventId===event.id));
  await assert.rejects(()=>eventInviteInbox(users[0]),/Event managers only/);
  assert.equal((await eventInviteInbox({...users[0],role:'creator'})).total,0);
  assert.equal((await registrationView(users[0],event.id)).guests.length,0);
  await assert.rejects(()=>changeRegistration(users[0],event.id,'approve',users[0].id),/Only the event/);
  await assert.rejects(()=>manageHostedEvent({...users[0],role:'creator'},event.id,'close-event'),/Only the event creator/);
  const approvals=await Promise.allSettled(users.slice(0,101).map(user=>changeRegistration(creator,event.id,'approve',user.id)));
  assert.equal(approvals.filter(result=>result.status==='fulfilled').length,100);
  assert.equal((await eventInviteInbox(creator)).total,1);
  let view=await registrationView(admin,event.id);assert.equal(view.approvedCount,100);assert.equal(view.capacity,100);
  await assert.rejects(()=>changeRegistration(users[101],event.id,'request'),/full/);
  const approvedUser=users.find(user=>view.guests.some(guest=>guest.id===user.id))!;
  const pendingUser=users.find(user=>!view.guests.some(guest=>guest.id===user.id))!;
  assert.equal((await registrationView(approvedUser,event.id)).canViewAttendees,true);
  await assert.rejects(()=>updateCuratedEvent(admin,event.id,{...inputFor(input),guestCapacity:99}),/capacity/);
  await changeRegistration(approvedUser,event.id,'cancel');
  const cancelled=await registrationView(approvedUser,event.id);assert.equal(cancelled.canViewAttendees,false);assert.equal(cancelled.guests.length,0);assert.equal(cancelled.approvedCount,99);
  await changeRegistration(creator,event.id,'approve',pendingUser.id);
  assert.equal((await registrationView(admin,event.id)).approvedCount,100);
  await manageHostedEvent(creator,event.id,'close-event');
  await assert.rejects(()=>changeRegistration(approvedUser,event.id,'request'),/closed/);
  await manageHostedEvent(admin,event.id,'reopen-event');
  await changeRegistration(pendingUser,event.id,'cancel');
  await changeRegistration(approvedUser,event.id,'request');await changeRegistration(admin,event.id,'approve',approvedUser.id);
  await manageHostedEvent(creator,event.id,'cancel-event');
  assert.equal((await eventInviteInbox(creator)).total,0);
  view=await registrationView(approvedUser,event.id);assert.equal(view.registrationStatus,'Cancelled');assert.equal(view.canViewAttendees,false);assert.deepEqual(view.guests,[]);
  await assert.rejects(()=>manageHostedEvent(admin,event.id,'reopen-event'),/cannot be reopened/);
  await assert.rejects(()=>changeRegistration(creator,event.id,'approve',pendingUser.id),/not accepting approvals/);
  await submitItem(admin,{...proposal,title:'DEMO · Admin invite inbox',id:'',createdBy:'',status:'pending',capacity:0,price:0,simulation:true},'admin-invite-inbox-test');
  const adminEvent=(await adminCatalogSnapshot(admin)).find(item=>item.title==='DEMO · Admin invite inbox')!;
  await changeRegistration(users[0],adminEvent.id,'request');
  await changeRegistration(users[0],adminEvent.id,'request');
  assert.equal((await eventInviteInbox(admin)).requests.filter(item=>item.eventId===adminEvent.id).length,1);
  assert.equal((await eventInviteInbox(creator)).requests.some(item=>item.eventId===adminEvent.id),false);
  const firstRequest=(await eventInviteInbox(admin)).requests.find(item=>item.eventId===adminEvent.id)!;
  await changeRegistration(users[0],adminEvent.id,'cancel');
  assert.equal((await eventInviteInbox(admin)).requests.some(item=>item.eventId===adminEvent.id),false);
  await new Promise(resolve=>setTimeout(resolve,2));
  await changeRegistration(users[0],adminEvent.id,'request');
  assert.notEqual((await eventInviteInbox(admin)).requests.find(item=>item.eventId===adminEvent.id)!.id,firstRequest.id);
  await changeRegistration(admin,adminEvent.id,'decline',users[0].id);
  assert.equal((await eventInviteInbox(admin)).requests.some(item=>item.eventId===adminEvent.id),false);
  assert.ok((await mobileBootstrap(approvedUser)).registrations?.some(item=>item.eventId===event.id));
  console.log(JSON.stringify({result:'passed',roles:['user','creator','admin'],capacity:100,concurrentApprovals:101,approvedAtPeak:100,checks:['creator submission stays private until admin review','native hosts need no external listing or profile URL','duplicate requests do not duplicate occupancy','self-approval and unrelated-creator control denied','101 concurrent approvals cannot exceed 100 places in local demo','cancellation releases capacity and revokes roster access','creator and admin can close/reopen registration','event cancellation is terminal and stops approvals','capacity cannot be reduced below confirmed places'],databaseConcurrencyTested:false},null,2));
}
function inputFor(event:ReturnType<typeof hostedDemoEvent>&{editorialPriority:{score:number;reason:string}}){
  const {id,capacity,price,createdBy,status,simulation,...input}=event;void id;void capacity;void price;void createdBy;void status;void simulation;return input;
}
main().catch(error=>{console.error(error);process.exitCode=1;});
