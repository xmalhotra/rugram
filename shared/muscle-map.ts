const areaTitle = new Map(muscleAreas.map(area => [area.id, area.title]));
const areaOrder = muscleAreas.map(area => area.id);

export function muscleMapFor(exerciseId: string): MuscleTag {
  const tag = exerciseMuscles[exerciseId];
  if (!tag) return { main: [], helpers: [] };
  return { main: [...tag.main], helpers: [...tag.helpers] };
}

/** An area that is main in any exercise stays main. Helpers are the rest. */
export function flowMuscleMap(exerciseIds: string[]): MuscleTag {
  const main = new Set<MuscleArea>();
  const helpers = new Set<MuscleArea>();
  for (const id of exerciseIds) {
    const tag = exerciseMuscles[id];
    if (!tag) continue;
    for (const area of tag.main) main.add(area);
    for (const area of tag.helpers) helpers.add(area);
  }
  for (const area of main) helpers.delete(area);
  const sort = (set: Set<MuscleArea>) => areaOrder.filter(area => set.has(area));
  return { main: sort(main), helpers: sort(helpers) };
}

/** Area titles for an exercise, so search can match words like quads and lats. */
export function muscleSearchText(exerciseId: string) {
  const tag = exerciseMuscles[exerciseId];
  if (!tag) return '';
  return [...tag.main, ...tag.helpers].map(area => areaTitle.get(area) ?? '').join(' ');
}
