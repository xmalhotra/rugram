export function prescriptionLabel(block:ExercisePrescription){return `${block.sets} ${block.sets===1?'set':'sets'} × ${block.mode==='reps'?`${block.reps} reps`:`${block.seconds}s hold`}${block.perSide?' per side':''} · rest ${block.restSeconds}s`;}
export function prescriptionVolume(block:ExercisePrescription){
  const amount=block.sets*(block.mode==='reps'?block.reps:block.seconds);
  return `${amount} ${block.mode==='reps'?'reps':'seconds of holds'}${block.perSide?` per side (${amount*2} total across both sides)`: ' in total'}`;
}
