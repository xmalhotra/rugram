const searchJoiner = new Set(['to', 'the', 'and', 'a', 'of', 'with']);

function searchText(text: string) {
  return text
    .toLowerCase()
    .replace(/-/g, ' ')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .replace(/\s+/g, ' ');
}

function searchWords(query: string) {
  const words = searchText(query).split(' ').filter(Boolean);
  if (words.length === 0) return [];
  const kept = words.filter(word => !searchJoiner.has(word));
  return kept.length ? kept : words;
}

/** Each word must match the start of its own word, so "to" does not match inside "Bottoms". */
function wordsAtStarts(text: string, words: string[]) {
  const tokens = searchText(text).split(' ').filter(Boolean);
  const used = new Set<number>();
  for (const word of words) {
    const index = tokens.findIndex((token, tokenIndex) => !used.has(tokenIndex) && token.startsWith(word));
    if (index < 0) return false;
    used.add(index);
  }
  return true;
}

export function searchExercises(query: string) {
  const words = searchWords(query);
  if (words.length === 0) return [];
  const exactQuery = searchText(query);
  const nameText = (item: GymExercise) => [item.name, ...(item.aliases ?? [])].join(' ');
  const exact = (item: GymExercise) =>
    [item.name, ...(item.aliases ?? [])].some(name => searchText(name) === exactQuery);
  const named = (item: GymExercise) => wordsAtStarts(nameText(item), words);
  return gymExercises
    .filter(item => {
      const place = station(item.station)?.title ?? '';
      return wordsAtStarts([item.name, ...(item.aliases ?? []), ...item.muscles, place, muscleSearchText(item.id)].join(' '), words);
    })
    .sort((a, b) => Number(exact(b)) - Number(exact(a)) || Number(named(b)) - Number(named(a)) || a.name.localeCompare(b.name));
}

