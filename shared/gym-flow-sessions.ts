import type { GymFlow, GymFlowItem } from './gym-flows';

/**
 * Catalogue sessions. Rest stays on the exercise's class unless a heavy main lift
 * is about 4 × 5–6 (180 seconds) or the conditioning finisher has its own plan.
 * A rep range uses pyramid. A fixed count stays straight.
 */
function work(
  exerciseId: string,
  sets: number,
  repsMin: number,
  repsMax: number,
  extra?: { scheme?: string; superset?: string; restSeconds?: number; hold?: boolean },
): GymFlowItem {
  if (extra?.hold) {
    return {
      exerciseId,
      sets,
      repsMin,
      repsMax,
      target: { kind: 'hold', minSeconds: repsMin, maxSeconds: repsMax },
      ...(extra.superset ? { superset: extra.superset } : {}),
      ...(extra.restSeconds != null ? { restSeconds: extra.restSeconds } : {}),
    };
  }
  const scheme = extra?.scheme ?? (repsMin !== repsMax ? 'pyramid' : undefined);
  return {
    exerciseId,
    sets,
    repsMin,
    repsMax,
    ...(scheme ? { scheme } : {}),
    ...(extra?.superset ? { superset: extra.superset } : {}),
    ...(extra?.restSeconds != null ? { restSeconds: extra.restSeconds } : {}),
  };
}

function session(id: string, title: string, level: string, goal: string, items: GymFlowItem[]): GymFlow {
  return { id, title, goal, level, items };
}

